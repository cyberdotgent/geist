const StrokeGlyph* stroke_glyph(char ch) {
  static const auto glyphs = [] {
    std::array<StrokeGlyph, glyph_entries.size()> out{};
    for (std::size_t i = 0; i < glyph_entries.size(); ++i) {
      const auto& entry = glyph_entries[i];
      out[i] = StrokeGlyph{entry.left, entry.right,
                           vertices.data() + entry.first, entry.count};
    }
    return out;
  }();
  const auto code = static_cast<unsigned char>(ch);
  if (code < 0x20 || code > 0x7e) {
    return nullptr;
  }
  return &glyphs[code - 0x20];
}

